/**
 * Formats a structured dive itinerary into an engaging, complete text document
 * suitable for sharing to the native share sheet or clipboard.
 */
function formatItineraryForShare(item) {
    const { title, budget, groupSize, activity, lengthOfStay, plan } = item;
    const planTitle = title || plan.summary?.overview || "Mabini Dive Adventure";
    const lines = [
        `🌊 SINSAY DIVE ITINERARY: ${planTitle}`,
        `📍 Mabini (Anilao), Batangas`,
    ];
    const specs = [];
    if (lengthOfStay)
        specs.push(`Duration: ${lengthOfStay}`);
    if (groupSize)
        specs.push(`Group: ${groupSize} diver${Number(groupSize) === 1 ? "" : "s"}`);
    if (activity)
        specs.push(`Activity: ${activity}`);
    if (budget)
        specs.push(`Budget: ₱${Number(budget).toLocaleString()}`);
    if (specs.length > 0) {
        lines.push(specs.join(" · "));
    }
    if (plan.summary?.overview) {
        lines.push(`\n${plan.summary.overview}`);
    }
    // Days breakdown
    if (Array.isArray(plan.days) && plan.days.length > 0) {
        lines.push("\n📅 DAILY ITINERARY:");
        plan.days.forEach((day) => {
            lines.push(`\nDay ${day.day}: ${day.title}`);
            day.activities?.forEach((act) => {
                lines.push(`  • ${act.time} (${act.period}): ${act.title}`);
                if (act.details) {
                    lines.push(`    ${act.details}`);
                }
            });
        });
    }
    // Suggested Dive Sites
    if (Array.isArray(plan.sites) && plan.sites.length > 0) {
        lines.push("\n🤿 SUGGESTED DIVE SITES:");
        plan.sites.forEach((site) => {
            const details = [site.depth, site.difficulty].filter(Boolean).join(", ");
            const suffix = details ? ` (${details})` : "";
            lines.push(`  • ${site.name}${suffix}`);
            if (site.description) {
                lines.push(`    ${site.description}`);
            }
        });
    }
    // Eco Alerts
    if (Array.isArray(plan.ecoAlerts) && plan.ecoAlerts.length > 0) {
        lines.push("\n🌿 MABINI ECO RULES & CONSERVATION:");
        plan.ecoAlerts.forEach((alert) => {
            lines.push(`  • ${alert}`);
        });
    }
    // Budget
    if (Array.isArray(plan.budgetBreakdown) && plan.budgetBreakdown.length > 0) {
        lines.push("\n💰 ESTIMATED BUDGET:");
        plan.budgetBreakdown.forEach((b) => {
            lines.push(`  • ${b.label}: ₱${Number(b.amount).toLocaleString()}`);
        });
        if (plan.budgetTotal) {
            lines.push(`  Total: ₱${Number(plan.budgetTotal).toLocaleString()}`);
        }
    }
    lines.push("\n— Generated by SINSAY AI Dive Assistant (Mabini, Batangas)");
    return lines.join("\n");
}
